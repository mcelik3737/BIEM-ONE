  await page.goto(`${origin}/projects?project=${fixture.projectId}&tab=operation`);
  await page.locator('.hr-project-cost').getByText(/4\.800,00/).waitFor();
  await page.reload();
  await page.locator('.hr-project-cost').getByText(/4\.800,00/).waitFor();
  await page.locator('.hr-project-cost').scrollIntoViewIfNeeded();
  await page.screenshot({path:`${output}/personnel-project-cost.png`,fullPage:true});
  pass('8 saat × 300 TRY puantaj onayı → iş dosyasında toplam maliyet ve kalıcılık');
