import assert from 'node:assert/strict';
export async function checkPersonnel({request, token, engineerToken, otherToken, engineer, other, project, pass, runId, base}) {
  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Europe/Istanbul',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
  const profile={fullName:`Kabul Personel ${runId}`,jobTitle:'RF saha teknisyeni',jobDescription:'Saha kurulumu ve ölçüm kayıtları',department:'Teknik',startDate:'2020-01-01',isActive:true,userId:engineer.id};
  const person=await request('/personnel',token,'POST',profile,201), pp=`/personnel/${person.id}`;
  await request('/personnel',token,'POST',{...profile,fullName:'Yinelenen bağlantı'},409);
  await request('/personnel',token,'POST',{...profile,userId:other.id},400);
  await request('/personnel',token,'POST',{...profile,userId:null,companyId:other.companyId},400);
  for(const path of ['/personnel',pp,'/personnel/options','/personnel/costs',`${pp}/time-entries`,`/personnel/project-costs/${project.id}`]) await request(path,engineerToken,'GET',undefined,403);
  await request(pp,otherToken,'GET',undefined,404);
  assert.deepEqual(await request('/personnel',otherToken),[]);
  assert.equal((await request(pp,token,'PATCH',{...profile,jobDescription:'Görev tanımı güncellendi'})).jobDescription,'Görev tanımı güncellendi');
  pass('Personel kartı, kullanıcı bağlantısı ve yönetici/şirket erişim sınırları');
  const rate={effectiveFrom:'2020-01-01',salaryBasis:'NET',monthlySalary:'40000',monthlyEmployerCost:'60000',monthlyHours:'200',currency:'TRY'};
  await request(`${pp}/compensations`,token,'POST',rate,201);
  await request(`${pp}/compensations`,token,'POST',rate,409);
  await request(`${pp}/compensations`,token,'POST',{...rate,effectiveFrom:'2020-02-01',monthlyHours:'0'},400);
  await request(`${pp}/compensations`,token,'POST',{...rate,effectiveFrom:'2020-02-01',monthlyEmployerCost:'999999999999',monthlyHours:'0.01'},400);
  assert.equal((await request(pp,token)).compensations[0].hourlyCost,'300.000000');
  pass('Tarihli ücret dönemleri ve 60.000 / 200 = 300 TRY saat maliyeti');
  const docInput={title:'Kabul İSG eğitim belgesi',isRequired:true,expiryRequired:true,issuedAt:'2020-01-01',expiresAt:'2040-01-01'};
  const doc=await request(`${pp}/documents`,token,'POST',docInput,201), dp=`${pp}/documents/${doc.id}`;
  assert.equal(doc.status,'MISSING');
  await request(`${dp}/review`,token,'POST',{},400);
  const pdf=Buffer.from('%PDF-1.4\n% BIEM synthetic acceptance document\n%%EOF');
  async function upload(path, body=pdf, mime='application/pdf', credential=token, expected=201) {
    const data=new FormData();data.append('file',new Blob([body],{type:mime}),'kabul-isg.pdf');
    const response=await fetch(`${base}${path}/file`,{method:'POST',headers:{Authorization:`Bearer ${credential}`},body:data});
    assert.equal(response.status,expected);return response.json();
  }
  await upload(dp,Buffer.from('<html>bad</html>'),'text/html',token,400);
  assert.equal((await upload(dp)).status,'PENDING_REVIEW');
  await upload(dp,pdf,'application/pdf',otherToken,404);
  await upload(dp,pdf,'application/pdf',engineerToken,403);
  assert.equal((await request(`${dp}/review`,token,'POST',{},201)).status,'CURRENT');
  const downloaded=await fetch(`${base}${dp}/file`,{headers:{Authorization:`Bearer ${token}`}});
  assert.equal(downloaded.status,200);assert.match(downloaded.headers.get('cache-control'),/no-store/);
  assert.equal(Buffer.from(await downloaded.arrayBuffer()).equals(pdf),true);
  await request(`${dp}/file`,engineerToken,'GET',undefined,403);
  await request(`${dp}/file`,otherToken,'GET',undefined,404);
  assert.equal(JSON.stringify(await request(pp,token)).includes('fileData'),false);
  pass('Özel İSG dosyası yükleme, kontrol onayı, indirme ve içerik erişim sınırları');
  await request(dp,token,'PATCH',{...docInput,expiresAt:'2020-02-01'});
  assert.equal((await request(pp,token)).documents[0].status,'EXPIRED');
  await request(`${dp}/review`,token,'POST',{},400);
  await request(dp,token,'PATCH',{...docInput,expiresAt:null});
  assert.equal((await request(pp,token)).documents[0].status,'MISSING_DATE');
  const soon=new Date(`${today}T00:00:00Z`);soon.setUTCDate(soon.getUTCDate()+10);
  await request(dp,token,'PATCH',{...docInput,expiresAt:soon.toISOString().slice(0,10)});
  assert.equal((await request(`${dp}/review`,token,'POST',{},201)).status,'EXPIRING');
  assert.equal((await request('/personnel',token)).find(p=>p.id===person.id).expiringDocuments,1);
  assert.equal((await upload(dp)).status,'PENDING_REVIEW');
  pass('İSG eksik tarih, süresi dolan/yaklaşan belge ve değişiklikte yeniden kontrol');
  const input={workDate:today,kind:'PROJECT',projectId:project.id,hours:'8',costMultiplier:'1',description:'Kabul saha çalışması'};
  const entry=await request(`${pp}/time-entries`,token,'POST',input,201), ep=`${pp}/time-entries/${entry.id}`;
  assert.deepEqual((await request(`/personnel/project-costs/${project.id}`,token)).totals,{});
  assert.equal((await request(`${ep}/approve`,token,'POST',{},201)).totalCost,'2400');
  assert.equal((await request(`/personnel/project-costs/${project.id}`,token)).totals.TRY,'2400.00');
  await request(`${pp}/time-entries`,token,'POST',{...input,hours:'0'},400);
  await request(`${pp}/time-entries`,token,'POST',{...input,hours:'24'},400);
  await request(`${pp}/time-entries`,token,'POST',{...input,workDate:'2019-01-01'},400);
  await request(`${pp}/time-entries`,token,'POST',{...input,kind:'ADMIN'},400);
  await request(`${ep}/approve`,engineerToken,'POST',{},403);
  await request(`${ep}/approve`,otherToken,'POST',{},404);
  await request(`${ep}/approve`,token,'POST',{},400);
  await request(`${pp}/compensations`,token,'POST',{...rate,effectiveFrom:today,monthlyEmployerCost:'90000'},201);
  assert.equal((await request(`${pp}/time-entries?month=${today.slice(0,7)}`,token)).find(e=>e.id===entry.id).totalCost,'2400');
  pass('Onaylı puantaj → iş maliyeti; yeni ücret dönemi geçmiş maliyeti değiştirmiyor');
  const attempts=await Promise.all([1,2].map(async n=>{
    const response=await fetch(`${base}${pp}/time-entries`,{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify({...input,hours:'10',description:`Paralel kayıt ${n}`})});return {status:response.status,data:await response.json()};
  }));
  assert.deepEqual(attempts.map(a=>a.status).sort(),[201,400]);
  const pending=attempts.find(a=>a.status===201).data;
  await request(`${pp}/time-entries/${pending.id}/void`,token,'POST',{reason:'Paralellik testi tamamlandı'},201);
  const extra=await request(`${pp}/time-entries`,token,'POST',{...input,hours:'1',description:'İptal testi'},201);
  assert.equal((await request(`${pp}/time-entries/${extra.id}/approve`,token,'POST',{},201)).totalCost,'450');
  await request(`${pp}/time-entries/${extra.id}/void`,token,'POST',{reason:'Düzeltme kaydı'},201);
  const costs=await request(`/personnel/project-costs/${project.id}`,token);
  assert.deepEqual(costs.totals,{TRY:'2400.00'});assert.equal(costs.pendingCount,0);
  pass('Eşzamanlı puantajda 24 saat sınırı; gerekçeli iptal ve maliyet geçmişi');
  const eur=await request('/personnel',token,'POST',{...profile,fullName:'Kabul idari personel',userId:null},201);
  await request(`/personnel/${eur.id}/compensations`,token,'POST',{...rate,monthlySalary:'500',monthlyEmployerCost:'1000',monthlyHours:'100',currency:'EUR'},201);
  const et=await request(`/personnel/${eur.id}/time-entries`,token,'POST',{...input,kind:'ADMIN',projectId:null,hours:'10'},201);
  await request(`/personnel/${eur.id}/time-entries/${et.id}/approve`,token,'POST',{},201);
  const all=await request(`/personnel/costs?month=${today.slice(0,7)}`,token);
  assert.deepEqual(all.totals,{TRY:'2400.00',EUR:'100.00'});
  assert.equal(all.rows.find(r=>r.currency==='EUR').label,'İdari çalışma');
  assert.deepEqual((await request('/personnel/costs',otherToken)).totals,{});
  await request(`/personnel/project-costs/${project.id}`,otherToken,'GET',undefined,404);
  for(const path of ['/users','/projects','/tasks','/files','/audit-logs']) assert.doesNotMatch(JSON.stringify(await request(path,token)),/monthlySalary|monthlyEmployerCost|fileData|hourlyCost/);
  for(const path of ['/projects','/tasks','/files']) assert.doesNotMatch(JSON.stringify(await request(path,engineerToken)),/monthlySalary|monthlyEmployerCost|fileData|hourlyCost/);
  for(const path of ['/users','/audit-logs']) await request(path,engineerToken,'GET',undefined,403);
  pass('Para birimi bazında iş/idari maliyet ayrımı; genel API' + "'lerde maaş ve belge sızıntısı yok");
  return {personId:person.id,personName:profile.fullName,personDocumentId:doc.id,engineerEmail:engineer.email,projectLaborTotal:'2400.00'};
}
